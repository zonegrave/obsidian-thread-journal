export type TranslationKey = keyof typeof ZH_TRANSLATIONS;

let currentLocale: Locale = 'zh';

export function resolveLocale(setting: LanguageSetting, hostLanguage: string): Locale {
	if (setting === 'zh' || setting === 'en') return setting;
	return hostLanguage.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function setLocale(locale: Locale): void {
	currentLocale = locale;
}

export function getLocale(): Locale {
	return currentLocale;
}

export function t(
	key: TranslationKey,
	values: Readonly<Record<string, string | number>> = {},
): string {
	return translate(currentLocale, key, values);
}

export function translate(
	locale: Locale,
	key: TranslationKey,
	values: Readonly<Record<string, string | number>> = {},
): string {
	const template = locale === 'zh' ? ZH_TRANSLATIONS[key] : key;
	return template.replace(/\{([^}]+)\}/g, (match, name: string) => {
		const value = values[name];
		return value === undefined ? match : String(value);
	});
}
